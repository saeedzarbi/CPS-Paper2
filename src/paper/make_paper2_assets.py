#!/usr/bin/env python3
"""Generate Paper 2 LaTeX tables, macros, and PDF figures from clean_v3 / extended results."""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.evaluation.clean_abr_eval import EXTENDED_TRACE_SETS, HEADLINE_TRACE_SETS
from src.evaluation.run_extended_validation import (
    ABLATION_ARMS,
    ABLATION_POLICIES,
    HORIZONS,
    OOD_POLICIES,
)

RES_V3 = ROOT / "results" / "clean_v3"
RES_EXT = ROOT / "results" / "clean_v3_extended"
PAPER = ROOT / "paper"
TAB = PAPER / "tables"
FIG = PAPER / "figures"

ARMS = ("raw", "static_conformal", "tube_conformal")
POLICIES = ("mpc", "greedy", "bba", "bola")
TRACE_JOBS = {"5g_markov": "5g_markov", "bb": "bb"}


def _load(path: Path) -> dict | None:
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def _mean(s: dict, arm: str, key: str) -> float:
    try:
        return float(s["arms"][arm][key]["mean"])
    except (KeyError, TypeError):
        return float("nan")


def _num(x: float, d: int = 2) -> str:
    return f"{x:.{d}f}" if x == x else "---"


def _pval(p: float) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "---"
    if p < 0.01:
        e = int(math.floor(math.log10(max(p, 1e-300))))
        m = p / (10 ** e)
        return f"${m:.1f}\\times10^{{{e}}}$"
    return f"{p:.2f}"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def gen_macros() -> None:
    lines = [
        "% Auto-generated by make_paper2_assets.py — do not edit by hand.",
        "",
    ]
    for pol in POLICIES:
        for tr, suffix in (("5g_markov", "FiveG"), ("bb", "BB")):
            s = _load(RES_V3 / f"{pol}_{tr}" / "summary.json")
            if not s:
                continue
            for arm, alab in (
                ("raw", "Raw"),
                ("static_conformal", "Static"),
                ("tube_conformal", "Tube"),
            ):
                base = f"P2{pol.capitalize()}{suffix}{alab}"
                lines.append(f"\\newcommand{{\\{base}Reb}}{{{_num(_mean(s, arm, 'rebuffer_total'))}}}")
                lines.append(
                    f"\\newcommand{{\\{base}Smooth}}{{{_num(_mean(s, arm, 'smooth_penalty_mean'), 3)}}}"
                )
                lines.append(f"\\newcommand{{\\{base}QoE}}{{{_num(_mean(s, arm, 'episodic_qoe'))}}}")
            comp = s.get("comparisons", {}).get("tube_conformal_vs_static_conformal", {})
            p = comp.get("rebuffer_total", {}).get("wilcoxon_p", float("nan"))
            lines.append(f"\\newcommand{{\\P2{pol.capitalize()}{suffix}PReb}}{{{_pval(p)}}}")

    for trace_key in EXTENDED_TRACE_SETS:
        for pol in OOD_POLICIES:
            s = _load(RES_EXT / "ood" / trace_key / pol / "summary.json")
            if not s:
                continue
            tk = trace_key.replace("_", "")
            lines.append(
                f"\\newcommand{{\\P2OOD{tk}{pol.capitalize()}TubeReb}}"
                f"{{{_num(_mean(s, 'tube_conformal', 'rebuffer_total'))}}}"
            )

    _write(TAB / "macros_paper2.tex", "\n".join(lines) + "\n")
    print(f"Wrote {TAB / 'macros_paper2.tex'} ({len(lines)} lines)")


def _main_table(trace: str, caption: str, label: str) -> str:
    rows = []
    for pol in POLICIES:
        s = _load(RES_V3 / f"{pol}_{trace}" / "summary.json")
        if not s:
            continue
        reb = [_num(_mean(s, a, "rebuffer_total")) for a in ARMS]
        sm = [_num(_mean(s, a, "smooth_penalty_mean"), 3) for a in ARMS]
        comp = s.get("comparisons", {}).get("tube_conformal_vs_static_conformal", {})
        p = _pval(comp.get("rebuffer_total", {}).get("wilcoxon_p", float("nan")))
        rows.append(f"    {pol} & {' & '.join(reb)} & {' & '.join(sm)} & {p} \\\\")
    body = "\n".join(rows)
    return (
        f"% Auto-generated\n"
        f"\\begin{{table}}[t]\n"
        f"\\centering\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{{label}}}\n"
        f"\\begin{{tabular}}{{lccc|ccc|c}}\n"
        f"    \\toprule\n"
        f"    & \\multicolumn{{3}}{{c}}{{Rebuffer (s/ep)}} & \\multicolumn{{3}}{{c}}{{Smoothness}} & \\\\\n"
        f"    Policy & raw & static & tube & raw & static & tube & $p$ \\\\\n"
        f"    \\midrule\n"
        f"{body}\n"
        f"    \\bottomrule\n"
        f"\\end{{tabular}}\n"
        f"\\end{{table}}\n"
    )


def gen_main_tables() -> None:
    _write(
        TAB / "table_main_5g.tex",
        _main_table("5g_markov", "Headline clean\\_v3 on 5G Markov traces.", "tab:main5g"),
    )
    _write(
        TAB / "table_main_bb.tex",
        _main_table("bb", "Headline clean\\_v3 on broadband (v18) traces.", "tab:mainbb"),
    )
    print("Wrote table_main_5g.tex, table_main_bb.tex")


def gen_extended_ood_table() -> None:
    rows = []
    for trace_key in EXTENDED_TRACE_SETS:
        for pol in OOD_POLICIES:
            s = _load(RES_EXT / "ood" / trace_key / pol / "summary.json")
            if not s:
                continue
            reb = [_num(_mean(s, a, "rebuffer_total")) for a in ARMS]
            comp = s.get("comparisons", {}).get("tube_conformal_vs_static_conformal", {})
            p = _pval(comp.get("rebuffer_total", {}).get("wilcoxon_p", float("nan")))
            rows.append(f"    {trace_key} & {pol} & {' & '.join(reb)} & {p} \\\\")
    text = (
        "% Auto-generated\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{OOD generalization (mean rebuffer s/ep).}\n\\label{tab:ood}\n"
        "\\begin{tabular}{llccc|c}\n\\toprule\n"
        "Trace & Policy & raw & static & tube & $p$ \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )
    _write(TAB / "table_extended_ood.tex", text)
    print("Wrote table_extended_ood.tex")


def gen_ablation_table() -> None:
    cols = list(ABLATION_ARMS)
    header = " & ".join(cols)
    rows = []
    for pol in ABLATION_POLICIES:
        s = _load(RES_EXT / "ablation" / pol / "summary.json")
        if not s:
            continue
        cells = [_num(_mean(s, a, "rebuffer_total")) for a in cols]
        rows.append(f"    {pol} & {' & '.join(cells)} \\\\")
    text = (
        "% Auto-generated\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Component ablation on 5G Markov (rebuffer s/ep).}\n\\label{tab:ablation}\n"
        f"\\begin{{tabular}}{{l{'c' * len(cols)}}}\n\\toprule\n"
        f"    Policy & {header} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )
    _write(TAB / "table_ablation.tex", text)
    print("Wrote table_ablation.tex")


def _save_pdf(fig: plt.Figure, name: str) -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    out = FIG / name
    fig.savefig(out, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Wrote {out}")


def fig1_rebuffer_smoothness() -> None:
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    x = np.arange(len(POLICIES))
    w = 0.25
    for ax, trace, title in zip(axes, ("5g_markov", "bb"), ("5G Markov", "Broadband")):
        reb = {a: [] for a in ARMS}
        for pol in POLICIES:
            s = _load(RES_V3 / f"{pol}_{trace}" / "summary.json")
            for a in ARMS:
                reb[a].append(_mean(s, a, "rebuffer_total") if s else float("nan"))
        for i, a in enumerate(ARMS):
            ax.bar(x + (i - 1) * w, reb[a], width=w, label=a.replace("_conformal", ""))
        ax.set_xticks(x)
        ax.set_xticklabels(POLICIES)
        ax.set_title(title)
        ax.set_ylabel("Rebuffer (s/ep)")
        ax.legend(fontsize=8)
    fig.suptitle("Headline rebuffer by arm")
    fig.tight_layout()
    _save_pdf(fig, "fig1_rebuffer_smoothness_bars.pdf")


def fig2_cdfs() -> None:
    import csv

    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    for ax, trace, title in zip(axes, ("5g_markov", "bb"), ("5G Markov", "Broadband")):
        for pol in ("mpc", "greedy"):
            path = RES_V3 / f"{pol}_{trace}" / "episodes.csv"
            if not path.is_file():
                continue
            by_arm: dict[str, list[float]] = {a: [] for a in ARMS}
            with open(path, newline="", encoding="utf-8") as f:
                for row in csv.DictReader(f):
                    if row["arm"] in by_arm:
                        by_arm[row["arm"]].append(float(row["rebuffer_total"]))
            for a in ARMS:
                if by_arm[a]:
                    xs = np.sort(by_arm[a])
                    ys = np.arange(1, len(xs) + 1) / len(xs)
                    ax.plot(xs, ys, label=f"{pol}/{a[:4]}")
        ax.set_title(title)
        ax.set_xlabel("Episode rebuffer (s)")
        ax.set_ylabel("CDF")
        ax.legend(fontsize=7)
    fig.tight_layout()
    _save_pdf(fig, "fig2_cdfs_5g_bb.pdf")


def fig3_qoe_sweep() -> None:
    """QoE vs conformal alpha (bba/bola extended sweep)."""
    fig, ax = plt.subplots(figsize=(6, 4))
    alphas = [0.05, 0.10, 0.15, 0.20]
    for pol, marker in (("bba", "o"), ("bola", "s")):
        qoes = []
        for alpha in alphas:
            s = _load(RES_EXT / "sensitivity" / "alpha" / f"{pol}_a{alpha:.2f}" / "summary.json")
            qoes.append(_mean(s, "tube_conformal", "episodic_qoe") if s else float("nan"))
        ax.plot(alphas, qoes, marker=marker, label=pol)
    ax.set_xlabel(r"Tube $\alpha$")
    ax.set_ylabel("Mean episodic QoE")
    ax.set_title("QoE vs coverage parameter")
    ax.legend()
    fig.tight_layout()
    _save_pdf(fig, "fig3_qoe_stall_weight_sweep.pdf")


def fig4_ablation_h_alpha() -> None:
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    for ax, pol in zip(axes, ABLATION_POLICIES):
        hs = list(HORIZONS)
        rebs = []
        for h in hs:
            s = _load(RES_EXT / "sensitivity" / "horizon" / f"{pol}_H{h}" / "summary.json")
            rebs.append(_mean(s, "tube_conformal", "rebuffer_total") if s else float("nan"))
        ax.plot(hs, rebs, "o-", label="rebuffer")
        ax.set_xlabel("Horizon H")
        ax.set_ylabel("Rebuffer (s/ep)")
        ax.set_title(pol)
        ax.set_xticks(hs)
    fig.suptitle("Horizon sweep (tube / static at H=1)")
    fig.tight_layout()
    _save_pdf(fig, "fig4_ablation_h_alpha.pdf")


def main() -> int:
    gen_macros()
    gen_main_tables()
    gen_extended_ood_table()
    gen_ablation_table()
    fig1_rebuffer_smoothness()
    fig2_cdfs()
    fig3_qoe_sweep()
    fig4_ablation_h_alpha()
    print("Paper 2 assets complete.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
