#!/usr/bin/env python3
"""
Wall-clock latency benchmark for the deterministic runtime shield
(``safe_adjust_action`` in ``src/training/safety_shield_v12.py``).

Motivation: main.ltx explicitly states that the shield's complexity is O(L)
"but runtime latency was not separately benchmarked." This script closes
that gap by timing the exact production shield function under realistic
per-chunk environment state (buffer, trace throughput, manifest sizes,
per-chunk VMAF), decoupled from policy inference (the shield's cost does not
depend on which policy proposed the action).

We do not need a trained PPO model here: the shield's latency depends only
on (env state, proposed action, config), not on how the action was chosen.
We drive the environment with a simple cycling action sequence so that the
shield is repeatedly exercised across the full representation ladder and
across the same four evaluation videos / trace pool used in Sec. 5 of the
paper, at the primary operating point (sigma_soft=0.8, tau=8).

Usage:
  cd new
  python src/paper/scripts/benchmark_shield_latency.py
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np

_NEW_ROOT = Path(__file__).resolve().parents[3]
sys.path.append(str(_NEW_ROOT))

from configs.paths import get_paths  # noqa: E402
from configs.videos import EVAL_VIDEOS, MAX_CHUNKS  # noqa: E402
from src.environment.abr_multi_env_v12 import ABREnv  # noqa: E402
from src.training.safety_shield_v12 import ShieldConfig, safe_adjust_action  # noqa: E402

PATHS = get_paths()
VIDEOS = list(EVAL_VIDEOS)
N_SEEDS = 17  # 12 videos x 17 seeds ≈ 204 CPS episodes
PRIMARY_CFG = ShieldConfig(level="light", vmaf_aware=True, soft_tolerance=0.8, vmaf_loss_budget=8.0)


def _make_env(video: str) -> ABREnv:
    return ABREnv(
        video_names=[video],
        trace_dir=str(PATHS["test_traces"]),
        vmaf_dir=str(PATHS["vmaf_scores"]),
        siti_dir=str(PATHS["content_features"]),
        max_chunks=MAX_CHUNKS,
        random_seed=12345,
        use_future=True,
        use_lyapunov=True,
    )


def benchmark() -> np.ndarray:
    """Return an array of per-call shield latencies, in microseconds."""
    latencies_us: list[float] = []
    n_levels = None

    for video in VIDEOS:
        env = _make_env(video)
        n_levels = len(env.BITRATE_LEVELS)
        for seed in range(N_SEEDS):
            obs, info = env.reset(seed=seed)
            done = False
            k = 0
            while not done and env.chunk_idx < env.max_chunks:
                # Cycle the raw proposal across the full ladder so the shield
                # is exercised both when it must intervene and when it can
                # pass the proposal through unchanged.
                raw_action = k % n_levels

                t0 = time.perf_counter()
                safe_action, _ = safe_adjust_action(env, raw_action, PRIMARY_CFG)
                t1 = time.perf_counter()
                latencies_us.append((t1 - t0) * 1e6)

                obs, _, done, _, info = env.step(int(safe_action))
                k += 1

    print(f"Representation ladder size L = {n_levels}")
    return np.asarray(latencies_us, dtype=float)


def main() -> None:
    # Warm-up pass (module import / first-call JIT-like caching effects in
    # numpy, disk-backed manifest lookups, etc.) is excluded from reported
    # statistics by discarding the first video's measurements below.
    lat = benchmark()
    warmup_n = 48 * N_SEEDS  # one video's worth of calls
    lat_steady = lat[warmup_n:]

    def pct(a: np.ndarray, q: float) -> float:
        return float(np.percentile(a, q))

    stats = {
        "n_calls": len(lat_steady),
        "mean_us": float(lat_steady.mean()),
        "median_us": pct(lat_steady, 50),
        "p95_us": pct(lat_steady, 95),
        "p99_us": pct(lat_steady, 99),
        "max_us": float(lat_steady.max()),
    }

    print("\nShield latency (steady-state, excludes first video as warm-up):")
    for k, v in stats.items():
        print(f"  {k}: {v:.3f}" if isinstance(v, float) else f"  {k}: {v}")

    out_dir = _NEW_ROOT / "src" / "paper" / "tables"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "macros_latency.tex"

    def macro(name: str, value: str) -> str:
        return f"\\providecommand{{\\{name}}}{{{value}}}"

    lines = [
        "% macros_latency.tex --- auto-generated by scripts/benchmark_shield_latency.py",
        "% Wall-clock latency of safe_adjust_action() (VMAF-aware shield, sigma_soft=0.8, tau=8),",
        f"% measured over {stats['n_calls']} calls across the 4-video/20-seed evaluation suite",
        "% on the machine used to run this script (single CPU core, Python, no GPU).",
        "\\makeatletter",
        macro("VLatMeanUs", f"{stats['mean_us']:.1f}"),
        macro("VLatMedianUs", f"{stats['median_us']:.1f}"),
        macro("VLatPNinetyNineUs", f"{stats['p99_us']:.1f}"),
        macro("VLatMaxUs", f"{stats['max_us']:.1f}"),
        macro("VLatNcalls", f"{stats['n_calls']}"),
        "\\makeatother",
    ]
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
