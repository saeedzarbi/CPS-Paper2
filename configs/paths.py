"""
Path configuration for the project.
UPDATED for IEEE TCSVT Submission Structure.
"""

import os
from pathlib import Path

# Project root directory (assumes this file is in new/configs/)
PROJECT_ROOT = Path(__file__).parent.parent


def _resolve_data_dir() -> Path:
    """Local ``data/`` or server mount via CPS_PAPER2_DATA_ROOT / CPS_DATA_ROOT."""
    for key in ("CPS_PAPER2_DATA_ROOT", "CPS_DATA_ROOT"):
        val = os.environ.get(key)
        if val:
            return Path(val).expanduser().resolve()
    return PROJECT_ROOT / "data"


# Data directories
DATA_DIR = _resolve_data_dir()
RAW_VIDEOS_DIR = DATA_DIR / "raw_videos"
ENCODED_VIDEOS_DIR = DATA_DIR / "encoded_videos"
VMAF_SCORES_DIR = DATA_DIR / "vmaf_scores"
CONTENT_FEATURES_DIR = DATA_DIR / "content_features"

# --- NEW STANDARDIZED PATHS (Generated by organize_data.py) ---
STANDARDIZED_DIR = DATA_DIR / "standardized"
TRAIN_TRACES_DIR = STANDARDIZED_DIR / "train_traces"
TEST_TRACES_DIR = STANDARDIZED_DIR / "test_traces"

# --- V18 provenance-correct datasets (trace *content* unchanged; Paper 2 uses OACS naming elsewhere) ---
TRAIN_TRACES_V18_DIR = STANDARDIZED_DIR / "train_traces_v18"
TEST_TRACES_V18_DIR = STANDARDIZED_DIR / "test_traces_v18"
TRAIN_TRACES_5G_V18_DIR = STANDARDIZED_DIR / "train_traces_5g_v18"
TEST_TRACES_5G_V18_DIR = STANDARDIZED_DIR / "test_traces_5g_v18"
# Real 5G (MMSys 2020 Irish traces); see docs/data_5g_real.md
TRAIN_TRACES_5G_IRISH_MMSYS20_DIR = STANDARDIZED_DIR / "train_traces_5g_irish_mmsys20"
TEST_TRACES_5G_IRISH_MMSYS20_DIR = STANDARDIZED_DIR / "test_traces_5g_irish_mmsys20"

# Results directories
RESULTS_DIR = PROJECT_ROOT / "results"
MODELS_DIR = RESULTS_DIR / "models"
LOGS_DIR = RESULTS_DIR / "logs"
PLOTS_DIR = RESULTS_DIR / "plots"

for directory in [RESULTS_DIR, MODELS_DIR, LOGS_DIR, PLOTS_DIR]:
    directory.mkdir(parents=True, exist_ok=True)


def get_paths():
    """Get all paths as a dictionary."""
    return {
        "project_root": PROJECT_ROOT,
        "data_dir": DATA_DIR,
        "raw_videos": RAW_VIDEOS_DIR,
        "encoded_videos": ENCODED_VIDEOS_DIR,
        "vmaf_scores": VMAF_SCORES_DIR,
        "content_features": CONTENT_FEATURES_DIR,
        "processed_traces": TRAIN_TRACES_DIR,
        "train_traces": TRAIN_TRACES_DIR,
        "test_traces": TEST_TRACES_DIR,
        "train_traces_v18": TRAIN_TRACES_V18_DIR,
        "test_traces_v18": TEST_TRACES_V18_DIR,
        "train_traces_5g_v18": TRAIN_TRACES_5G_V18_DIR,
        "test_traces_5g_v18": TEST_TRACES_5G_V18_DIR,
        "train_traces_5g_irish_mmsys20": TRAIN_TRACES_5G_IRISH_MMSYS20_DIR,
        "test_traces_5g_irish_mmsys20": TEST_TRACES_5G_IRISH_MMSYS20_DIR,
        "results": RESULTS_DIR,
        "models": MODELS_DIR,
        "logs": LOGS_DIR,
        "plots": PLOTS_DIR,
    }


if __name__ == "__main__":
    print("\nProject Paths Verification:\n")
    paths = get_paths()
    all_good = True
    critical = {
        "train_traces_v18",
        "test_traces_v18",
        "train_traces_5g_v18",
        "test_traces_5g_v18",
        "vmaf_scores",
    }
    for name, path in paths.items():
        exists = path.exists()
        mark = "OK" if exists else "MISSING"
        print(f"  [{mark:7s}] {name:22s}: {path}")
        if name in critical and not exists:
            all_good = False
    print("-" * 50)
    if DATA_DIR != PROJECT_ROOT / "data":
        print(f"  (data root override: {DATA_DIR})")
    if not all_good:
        print("WARNING: required Paper 2 data paths are missing.")
        print("  Local: see docs/data_setup.md")
        print("  Server: set CPS_PAPER2_DATA_ROOT to your mounted dataset.")
    else:
        print("Data layout OK.")
